#!/usr/bin/env python3
"""Write dist/_headers: the Content-Security-Policy and other response headers.

Run after `trunk build --release`. Cloudflare Workers static assets reads
`_headers` from the asset directory and applies it to every response; the file
itself is not served.

The policy cannot be a fixed file, because trunk injects an inline
`<script type="module">` loader into index.html, and that script names the
content-hashed .js and .wasm files. So its text changes with every build, and
a strict `script-src` (no 'unsafe-inline') has to allow it by hash. This script
hashes each inline script in dist/index.html and puts the hashes in the
policy. Everything else in the file is the fixed HEADERS_TEMPLATE below, which
scripts/privacy_check.py imports: the guard recomputes the hashes and requires
dist/_headers to be exactly this script's output.

Usage: python3 scripts/write_headers.py [DIST_DIR]   (default: dist)
"""

from __future__ import annotations

import base64
import hashlib
import re
import sys
from html.parser import HTMLParser
from pathlib import Path


class InlineScripts(HTMLParser):
    """Collects the exact text of every inline <script> (one with no src)."""

    def __init__(self) -> None:
        super().__init__(convert_charrefs=False)
        self.scripts: list[str] = []
        self._buf: list[str] | None = None

    def handle_starttag(self, tag, attrs):
        if tag == "script" and not any(name == "src" for name, _ in attrs):
            self._buf = []

    def handle_endtag(self, tag):
        if tag == "script" and self._buf is not None:
            self.scripts.append("".join(self._buf))
            self._buf = None

    def handle_data(self, data):
        if self._buf is not None:
            self._buf.append(data)


def inline_script_hashes(html: str) -> list[str]:
    parser = InlineScripts()
    parser.feed(html)
    parser.close()
    out = []
    for text in parser.scripts:
        digest = hashlib.sha256(text.encode("utf-8")).digest()
        out.append("'sha256-" + base64.b64encode(digest).decode("ascii") + "'")
    return out


# The one canonical dist/_headers. scripts/privacy_check.py imports this and
# requires dist/_headers to equal it byte for byte (after normalizing line
# endings), so any edit to the deployed file, such as another path block, a
# `!` header-removal line, a Report-Only policy or a dropped directive, fails
# the guard. The only variable part is SCRIPT_HASHES: the 'sha256-...' hash
# of each inline script in dist/index.html (trunk's loader).
SCRIPT_HASHES = "{SCRIPT_HASHES}"

# Everything is denied unless listed. No directive names another origin.
# base-uri, form-action and frame-ancestors do not fall back to default-src,
# so they are set explicitly.
CSP_DIRECTIVES = (
    "default-src 'none'",
    # Own .js glue, trunk's inline loader (by hash), and wasm compilation.
    f"script-src 'self' 'wasm-unsafe-eval' {SCRIPT_HASHES}",
    "style-src 'self'",
    # Pasted images are shown from blob:/data: URLs created in the page.
    "img-src 'self' blob: data:",
    # The wasm-bindgen loader fetches the .wasm from this origin. Nothing
    # else may connect anywhere.
    "connect-src 'self'",
    "base-uri 'none'",
    "form-action 'none'",
    "frame-ancestors 'none'",
)

HEADERS_TEMPLATE = (
    "# Generated by scripts/write_headers.py after trunk build. Do not edit\n"
    "# dist/_headers by hand; change the script instead. scripts/privacy_check.py\n"
    "# fails unless this file is exactly the script's output.\n"
    "/*\n"
    f"  Content-Security-Policy: {'; '.join(CSP_DIRECTIVES)}\n"
    "  X-Content-Type-Options: nosniff\n"
    "  Referrer-Policy: no-referrer\n"
    "  Cross-Origin-Opener-Policy: same-origin\n"
    "  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()\n"
)

HASH_SOURCE = re.compile(r"^'sha256-[A-Za-z0-9+/]+={0,2}'$")


def template_policy() -> str:
    """The CSP line of the template, with the placeholder still in it."""
    return "; ".join(CSP_DIRECTIVES)


def render_headers(script_hashes: list[str]) -> str:
    """The template with the inline-script hashes filled in."""
    if not script_hashes:
        raise ValueError("no inline script hashes; expected trunk's loader")
    for h in script_hashes:
        if not HASH_SOURCE.match(h):
            raise ValueError(f"not a CSP sha256 source: {h!r}")
    assert HEADERS_TEMPLATE.count(SCRIPT_HASHES) == 1
    return HEADERS_TEMPLATE.replace(SCRIPT_HASHES, " ".join(script_hashes))


def expected_headers(dist: Path) -> str:
    """What dist/_headers must contain for this build of dist/index.html."""
    html = (dist / "index.html").read_text(encoding="utf-8")
    return render_headers(inline_script_hashes(html))


def main(argv: list[str]) -> int:
    dist = Path(argv[1] if len(argv) > 1 else "dist")
    index = dist / "index.html"
    if not index.is_file():
        print(f"write_headers: {index} not found; run trunk build first", file=sys.stderr)
        return 1
    try:
        text = expected_headers(dist)
    except ValueError as e:
        print(f"write_headers: {e}", file=sys.stderr)
        return 1
    out = dist / "_headers"
    out.write_bytes(text.encode("utf-8"))
    n = len(inline_script_hashes(index.read_text(encoding="utf-8")))
    print(f"write_headers: wrote {out} ({n} inline script hash(es))")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
